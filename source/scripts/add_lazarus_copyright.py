#!/usr/bin/env python3
"""Add copyright banner to Lazarus/*.pas component units."""
from pathlib import Path
import re

ROOT = Path(r"H:/Devel/CPP/libZFork/Lazarus")

COPY_BLOCK = """\
  Copyright (C) 2026 Matthias Stoltze
  https://solid-software.net
"""

SKIP = {"lazlibzfork.pas"}  # auto-generated by Lazarus


def ensure_copyright(text: str) -> str:
    if "Copyright (C) 2026 Matthias Stoltze" in text and "solid-software.net" in text[:800]:
        return text  # already present near top

    # Pattern A: classic {****** ... ******} banner
    m = re.match(
        r"^(\{[*]{10,}[^\n]*\n)(.*?)(\*{10,}\})",
        text,
        re.S,
    )
    if m:
        head, body, close = m.group(1), m.group(2), m.group(3)
        # drop old copyright lines if any
        lines = body.splitlines(True)
        filtered = [
            ln
            for ln in lines
            if "Copyright" not in ln and "solid-software.net" not in ln
        ]
        # insert copyright after first content line or at start of body
        new_body = COPY_BLOCK + "".join(filtered)
        if not new_body.endswith("\n"):
            new_body += "\n"
        rest = text[m.end() :]
        return head + new_body + close + rest

    # Pattern B: other { ... } comment at start
    m2 = re.match(r"^(\{[^}]*\})\s*\n", text, re.S)
    if m2:
        banner = (
            "{******************************************************************************\n"
            + COPY_BLOCK
            + "******************************************************************************}\n"
        )
        return banner + text

    # No banner: prepend
    banner = (
        "{******************************************************************************\n"
        + COPY_BLOCK
        + "******************************************************************************}\n"
    )
    return banner + text


def main() -> None:
    n = 0
    for path in sorted(ROOT.glob("*.pas")):
        if path.name in SKIP:
            continue
        raw = path.read_text(encoding="utf-8", errors="replace")
        new = ensure_copyright(raw)
        if new != raw:
            path.write_text(new, encoding="utf-8", newline="\n")
            n += 1
            print("updated", path.name)
        else:
            print("ok     ", path.name)
    print(f"done, {n} files changed")


if __name__ == "__main__":
    main()
